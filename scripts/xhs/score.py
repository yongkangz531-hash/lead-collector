ORDER = {"高": 0, "中": 1, "低": 2}


def score_rows(rows):
    out = []
    for r in rows:
        t = (r.get("text") or "").strip()
        if len(t) < 3:
            continue
        low = any(w in t for w in LOW)
        high = any(w in t for w in HIGH)
        if high and not low:
            intent = "高"
        elif low and not high:
            intent = "低"
        elif high and low:
            intent = "中"
        elif any(w in t for w in ["想", "求", "怎么", "可以", "能", "有没有"]):
            intent = "中"
        else:
            intent = "低"

        need = "了解详情"
        for words, label in NEED:
            if any(w in t for w in words):
                need = label
                break

        out.append({
            "name": r.get("name", ""),
            "platform": r.get("platform", "小红书"),
            "note": r.get("note", ""),
            "note_id": r.get("note_id", ""),
            "note_url": r.get("note_url", ""),
            "user_url": r.get("user_url", ""),
            "text": t,
            "intent": intent,
            "need": need,
            "reply": REPLY.get(need, REPLY["了解详情"]),
            "like": r.get("like", ""),
            "ip": r.get("ip", ""),
            "ctime": r.get("ctime", ""),
        })
    out.sort(key=lambda x: ORDER[x["intent"]])
    return out


def stats(rows):
    return {
        "all": len(rows),
        "hi": sum(1 for r in rows if r["intent"] == "高"),
        "mid": sum(1 for r in rows if r["intent"] == "中"),
        "lo": sum(1 for r in rows if r["intent"] == "低"),
    }
